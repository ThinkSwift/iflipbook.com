#!/usr/bin/env python3
"""Build draw/otto-data.js (and draw/og.png) from Otto as he ships in the iFlipbook app.

Source: the app's starter flipbook "Otto says hello"
(iFlipbook/StarterFlipbooks/otto-hello-episode.iflipbook.json) — six hand-drawn poses with
in-betweens, the same file the app opens on first run. Nothing here is engine output.

Usage: python3 draw/tools/make-otto.py [path/to/iFlipbook repo]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DRAW = os.path.dirname(HERE)
APP = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Projects/iFlipbook")
SRC = os.path.join(APP, "iFlipbook/StarterFlipbooks/otto-hello-episode.iflipbook.json")


def r(v):
    return int(round(v))


def load():
    d = json.load(open(SRC))
    poses = []
    for f in d["frames"]:
        shapes = []
        for layer in sorted(f["layers"], key=lambda l: l.get("zOrder", 0)):
            if layer.get("isHidden"):
                continue
            for it in layer["items"]:
                s = it["shape"]
                paint = s["style"]["paint"]
                t = s["transform"]
                assert t["rotation"] == 0 and t["scale"] == {"x": 1, "y": 1} and t["translation"] == {"x": 0, "y": 0}
                paths = []
                for p in s["paths"]:
                    nums = []
                    for v, i, o in zip(p["vertices"], p["inTangents"], p["outTangents"]):
                        nums += [r(v["x"]), r(v["y"]), r(i["x"]), r(i["y"]), r(o["x"]), r(o["y"])]
                    paths.append([1 if p["isClosed"] else 0] + nums)
                shapes.append({
                    "f": 1 if "fill" in paint else 0,
                    "w": r(paint["stroke"]["width"]) if "stroke" in paint else 0,
                    "p": paths,
                })
        poses.append(shapes)
    tweens = []
    for i, tr in enumerate(d["frameTransitions"]):
        k = tr.get("tweenCount", 0)
        if k and i + 1 < len(poses):
            a, b = poses[i], poses[i + 1]
            same = len(a) == len(b) and all(
                len(sa["p"]) == len(sb["p"]) and all(len(pa) == len(pb) for pa, pb in zip(sa["p"], sb["p"]))
                for sa, sb in zip(a, b))
            if not same:
                k = 0
        tweens.append(k)
    return d, poses, tweens


def write_js(d, poses, tweens):
    data = {"size": d["canvasSize"]["width"], "fps": d["defaultTransitionFPS"], "tweens": tweens, "poses": poses}
    js = ("// Otto as he ships in iFlipbook: the starter flipbook \"Otto says hello\" (six poses, in-betweens).\n"
          "// Generated by draw/tools/make-otto.py — do not edit by hand.\n"
          "// Path: [closed, x, y, inX, inY, outX, outY, ...] (tangents relative to their vertex), 512 × 512.\n"
          "export const OTTO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    out = os.path.join(DRAW, "otto-data.js")
    open(out, "w").write(js)
    print(out, len(js), "bytes")


def flatten(path, n=12):
    closed, nums = path[0], path[1:]
    V = [(nums[i], nums[i + 1]) for i in range(0, len(nums), 6)]
    I = [(nums[i + 2], nums[i + 3]) for i in range(0, len(nums), 6)]
    O = [(nums[i + 4], nums[i + 5]) for i in range(0, len(nums), 6)]
    pts = [V[0]]
    order = list(range(1, len(V))) + ([0] if closed else [])
    for k in order:
        j = k - 1 if k else len(V) - 1
        p0, p3 = V[j], V[k]
        p1 = (p0[0] + O[j][0], p0[1] + O[j][1])
        p2 = (p3[0] + I[k][0], p3[1] + I[k][1])
        for s in range(1, n + 1):
            t = s / n
            u = 1 - t
            pts.append((u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0],
                        u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1]))
    return pts, closed


def write_og(poses):
    """1200 × 630 card: Otto pointing at a page with a ball in three frames (onion skin)."""
    from PIL import Image, ImageDraw
    S = 2  # supersample
    W, H = 1200 * S, 630 * S
    im = Image.new("RGB", (W, H), (11, 15, 26))
    dr = ImageDraw.Draw(im)
    paper = (251, 248, 241)
    ink = (26, 26, 30)
    dr.rounded_rectangle((60 * S, 60 * S, 1140 * S, 570 * S), radius=36 * S, fill=paper)

    def pt(x, y, ox, oy, sc):
        return (ox + x * sc, oy + y * sc)

    sc, ox, oy = 1.05 * S, 120 * S, 30 * S
    for shape in poses[2]:
        for path in shape["p"]:
            pts, closed = flatten(path)
            pts = [pt(x, y, ox, oy, sc) for x, y in pts]
            if shape["f"]:
                dr.polygon(pts, fill=(255, 255, 255))
            if shape["w"]:
                w = shape["w"] * sc
                seq = pts + ([pts[0]] if closed else [])
                dr.line(seq, fill=ink, width=int(w))
                for x, y in seq:  # round caps and joins
                    dr.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=ink)

    # The ball page: three frames on one sheet, older ones faint.
    def ball(cx, cy, rx, ry, col, w):
        dr.ellipse(((cx - rx) * S, (cy - ry) * S, (cx + rx) * S, (cy + ry) * S), outline=col, width=w * S)

    faint = (214, 211, 205)
    mid = (170, 168, 163)
    ball(820, 170, 52, 52, faint, 7)
    ball(820, 488, 66, 36, mid, 7)
    ball(820, 330, 52, 52, ink, 8)
    dr.line((690 * S, 528 * S, 950 * S, 528 * S), fill=(200, 196, 188), width=4 * S)
    im = im.resize((1200, 630), Image.LANCZOS)
    out = os.path.join(DRAW, "og.png")
    im.save(out, optimize=True)
    print(out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    d, poses, tweens = load()
    write_js(d, poses, tweens)
    write_og(poses)
